#!/usr/bin/env python3
"""Neat Narrative Co. — webfont vendor tool.

Downloads the same WebP-compressed ``woff2`` files the Google Fonts CSS API
would serve, keeps the ``latin`` and ``latin-ext`` subsets (everything the
site's English copy needs) and writes ``assets/css/fonts.css`` pointing at
local copies.

Why vendor rather than link: a stylesheet hosted by a third party means every
visitor's IP address is disclosed to that third party for a purely cosmetic
feature, and it makes the site unusable offline and slower on first paint.
Self-hosted, the site makes no external requests at all.

Run from the project root:

    python tools/vendor_fonts.py

Safe to re-run: it overwrites the vendored files and the generated stylesheet.
"""

from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "assets" / "fonts"
CSS_OUT = ROOT / "assets" / "css" / "fonts.css"

API = (
    "https://fonts.googleapis.com/css2"
    "?family=Barlow+Condensed:ital,wght@0,400;0,500;0,600;0,700;1,600"
    "&family=Cormorant+Garamond:ital,wght@0,400;0,500;0,600;1,400;1,500;1,600"
    "&family=Inter:wght@400;500;600"
    "&display=swap"
)

# The API serves different formats per user agent; the woff2 branch is the one
# every browser this site supports will use.
UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/125.0.0.0 Safari/537.36"
)

KEEP_SUBSETS = {"latin", "latin-ext"}
TIMEOUT_SECONDS = 60

BLOCK = re.compile(
    r"/\*\s*(?P<subset>[a-z-]+)\s*\*/\s*@font-face\s*\{(?P<body>[^}]*)\}", re.S
)
FAMILY = re.compile(r"font-family:\s*'(?P<value>[^']+)'")
STYLE = re.compile(r"font-style:\s*(?P<value>[a-z]+)")
WEIGHT = re.compile(r"font-weight:\s*(?P<value>[0-9]+)")
RANGE = re.compile(r"unicode-range:\s*(?P<value>[^;]+);")
URL = re.compile(r"url\((?P<value>[^)]+)\)")


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(request, timeout=TIMEOUT_SECONDS) as response:
        return response.read()


def slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")


def build_face(css: str) -> tuple[list[str], int]:
    lines: list[str] = []
    written = 0

    for match in BLOCK.finditer(css):
        subset = match.group("subset")
        if subset not in KEEP_SUBSETS:
            continue

        body = match.group("body")
        family = FAMILY.search(body)
        style = STYLE.search(body)
        weight = WEIGHT.search(body)
        span = RANGE.search(body)
        url = URL.search(body)
        if not (family and style and weight and span and url):
            continue

        name = "{}-{}-{}-{}.woff2".format(
            slug(family.group("value")),
            subset,
            weight.group("value"),
            style.group("value"),
        )
        source = url.group("value").strip("'\"")
        (FONTS / name).write_bytes(fetch(source))
        written += 1

        lines.append("/* {} */".format(subset))
        lines.append("@font-face {")
        lines.append("  font-family: '{}';".format(family.group("value")))
        lines.append("  font-style: {};".format(style.group("value")))
        lines.append("  font-weight: {};".format(weight.group("value")))
        lines.append("  font-display: swap;")
        lines.append("  src: url('../fonts/{}') format('woff2');".format(name))
        lines.append("  unicode-range: {};".format(span.group("value").strip()))
        lines.append("}")
        lines.append("")

    return lines, written


HEADER = """/* ==========================================================================
   Neat Narrative Co. — self-hosted webfonts
   --------------------------------------------------------------------------
   Generated by tools/vendor_fonts.py. Do not edit by hand — re-run the tool
   to refresh.

   Only the latin and latin-ext subsets are kept, which is everything the
   site's English copy needs. Serving the fonts from this domain means no
   visitor IP is disclosed to a third party for a cosmetic feature.
   ========================================================================== */

"""


def main() -> int:
    css = fetch(API).decode("utf-8")
    FONTS.mkdir(parents=True, exist_ok=True)

    lines, written = build_face(css)
    if not written:
        print("Nothing parsed — the API response was not in the expected shape.")
        return 1

    CSS_OUT.parent.mkdir(parents=True, exist_ok=True)
    CSS_OUT.write_text(HEADER + "\n".join(lines), encoding="utf-8")

    print("Vendored {count} font file(s) into {folder}".format(count=written, folder=FONTS))
    print("Wrote {path}".format(path=CSS_OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
